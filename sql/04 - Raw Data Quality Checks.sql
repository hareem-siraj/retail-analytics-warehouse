SELECT COUNT(*) AS MISSING_EMAILS
FROM RETAIL_ANALYTICS.RAW.CUSTOMERS
WHERE EMAIL IS NULL OR TRIM(EMAIL) = '';

SELECT
    ORDER_LINE_ID,
    COUNT(*) AS RECORD_COUNT
FROM RETAIL_ANALYTICS.RAW.ORDERS
GROUP BY ORDER_LINE_ID
HAVING COUNT(*) > 1
ORDER BY RECORD_COUNT DESC;

SELECT COUNT(*) AS INVALID_QUANTITIES
FROM RETAIL_ANALYTICS.RAW.ORDERS
WHERE TRY_TO_NUMBER(QUANTITY) <= 0;

SELECT COUNT(*) AS INVALID_PRICES
FROM RETAIL_ANALYTICS.RAW.ORDERS
WHERE TRY_TO_DECIMAL(UNIT_PRICE, 10, 2) <= 0;

SELECT COUNT(*) AS UNKNOWN_CUSTOMERS
FROM RETAIL_ANALYTICS.RAW.ORDERS o
LEFT JOIN RETAIL_ANALYTICS.RAW.CUSTOMERS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.CUSTOMER_ID IS NULL;

SELECT COUNT(*) AS UNKNOWN_PRODUCTS
FROM RETAIL_ANALYTICS.RAW.ORDERS o
LEFT JOIN RETAIL_ANALYTICS.RAW.PRODUCTS p
    ON o.PRODUCT_ID = p.PRODUCT_ID
WHERE p.PRODUCT_ID IS NULL;