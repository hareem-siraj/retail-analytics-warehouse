
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE RETAIL_ANALYTICS;

-- MODEL 1: Customer dimension
CREATE OR REPLACE VIEW ANALYTICS.DIM_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    EMAIL,
    CITY,
    SEGMENT,
    UPDATED_AT
FROM STAGING.STG_CUSTOMERS;


-- MODEL 2: Product dimension
CREATE OR REPLACE VIEW ANALYTICS.DIM_PRODUCTS AS
SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    UNIT_PRICE AS CURRENT_PRODUCT_PRICE
FROM STAGING.STG_PRODUCTS;


-- MODEL 3: Sales fact
CREATE OR REPLACE VIEW ANALYTICS.FACT_SALES AS
SELECT
    o.ORDER_LINE_ID,
    o.ORDER_ID,
    o.ORDER_DATE,
    o.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CITY AS CUSTOMER_CITY,
    c.SEGMENT AS CUSTOMER_SEGMENT,
    o.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.CATEGORY AS PRODUCT_CATEGORY,
    o.QUANTITY,
    o.UNIT_PRICE,
    o.QUANTITY * o.UNIT_PRICE AS LINE_REVENUE,
    o.STATUS,
    o.UPDATED_AT
FROM STAGING.STG_ORDERS o
INNER JOIN ANALYTICS.DIM_CUSTOMERS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID
INNER JOIN ANALYTICS.DIM_PRODUCTS p
    ON o.PRODUCT_ID = p.PRODUCT_ID
WHERE o.STATUS = 'completed'
  AND o.IS_VALID_QUANTITY
  AND o.IS_VALID_PRICE
  AND o.IS_VALID_ORDER_DATE;



//verify
SELECT 'DIM_CUSTOMERS' AS MODEL, COUNT(*) AS ROW_COUNT
FROM ANALYTICS.DIM_CUSTOMERS

UNION ALL

SELECT 'DIM_PRODUCTS', COUNT(*)
FROM ANALYTICS.DIM_PRODUCTS

UNION ALL

SELECT 'FACT_SALES', COUNT(*)
FROM ANALYTICS.FACT_SALES;


//monthly revenue

SELECT
    DATE_TRUNC('MONTH', ORDER_DATE) AS SALES_MONTH,
    COUNT(*) AS COMPLETED_ORDER_LINES,
    SUM(QUANTITY) AS UNITS_SOLD,
    ROUND(SUM(LINE_REVENUE), 2) AS TOTAL_REVENUE
FROM ANALYTICS.FACT_SALES
GROUP BY DATE_TRUNC('MONTH', ORDER_DATE)
ORDER BY SALES_MONTH;
