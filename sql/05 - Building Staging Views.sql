
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE RETAIL_ANALYTICS;

-- 1. Clean customers
CREATE OR REPLACE VIEW STAGING.STG_CUSTOMERS AS
SELECT
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(CUSTOMER_NAME) AS CUSTOMER_NAME,
    NULLIF(TRIM(EMAIL), '') AS EMAIL,
    INITCAP(TRIM(CITY)) AS CITY,
    TRIM(SEGMENT) AS SEGMENT,
    TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT
FROM RAW.CUSTOMERS;


-- 2. Clean products
CREATE OR REPLACE VIEW STAGING.STG_PRODUCTS AS
SELECT
    TRIM(PRODUCT_ID) AS PRODUCT_ID,
    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,
    INITCAP(TRIM(CATEGORY)) AS CATEGORY,
    TRY_TO_DECIMAL(UNIT_PRICE, 10, 2) AS UNIT_PRICE
FROM RAW.PRODUCTS;


-- 3. Deduplicate and clean orders
CREATE OR REPLACE VIEW STAGING.STG_ORDERS AS
WITH deduplicated AS (
    SELECT
        *,
        ROW_NUMBER() OVER (
            PARTITION BY ORDER_LINE_ID
            ORDER BY TRY_TO_TIMESTAMP_NTZ(LOADED_AT) DESC
        ) AS ROW_NUM
    FROM RAW.ORDERS
)
SELECT
    TRIM(ORDER_LINE_ID) AS ORDER_LINE_ID,
    TRIM(ORDER_ID) AS ORDER_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(PRODUCT_ID) AS PRODUCT_ID,

    COALESCE(
        TRY_TO_DATE(ORDER_DATE, 'YYYY-MM-DD'),
        TRY_TO_DATE(ORDER_DATE, 'DD/MM/YYYY')
    ) AS ORDER_DATE,

    TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
    TRY_TO_DECIMAL(UNIT_PRICE, 10, 2) AS UNIT_PRICE,
    LOWER(TRIM(STATUS)) AS STATUS,
    TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,
    TRY_TO_TIMESTAMP_NTZ(LOADED_AT) AS LOADED_AT,

    COALESCE(TRY_TO_NUMBER(QUANTITY) > 0, FALSE)
        AS IS_VALID_QUANTITY,

    COALESCE(
        TRY_TO_DECIMAL(UNIT_PRICE, 10, 2) > 0,
        FALSE
    ) AS IS_VALID_PRICE,

    COALESCE(
        TRY_TO_DATE(ORDER_DATE, 'YYYY-MM-DD'),
        TRY_TO_DATE(ORDER_DATE, 'DD/MM/YYYY')
    ) IS NOT NULL AS IS_VALID_ORDER_DATE

FROM deduplicated
WHERE ROW_NUM = 1;



SELECT 'STG_CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM STAGING.STG_CUSTOMERS

UNION ALL

SELECT 'STG_PRODUCTS', COUNT(*)
FROM STAGING.STG_PRODUCTS

UNION ALL

SELECT 'STG_ORDERS', COUNT(*)
FROM STAGING.STG_ORDERS;

SELECT
    COUNT_IF(NOT IS_VALID_QUANTITY) AS INVALID_QUANTITIES,
    COUNT_IF(NOT IS_VALID_PRICE) AS INVALID_PRICES,
    COUNT_IF(NOT IS_VALID_ORDER_DATE) AS INVALID_DATES
FROM STAGING.STG_ORDERS;